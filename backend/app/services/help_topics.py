"""Beginner-facing explanations for every important concept (novice mode).

One source of truth for the plain-language help shown in the Web UI, the Mini
App and the Setup Wizard. Each topic answers the questions a new user asks:

* **what** — what is this?
* **why** — why is it needed?
* **effect** — what will happen?
* **when_off** — what happens if you turn it off / don't use it?
* **safe_default** — the safe default value / behaviour.

Texts are deliberately non-technical and Russian-first (docs/UI.md). The catalog
is served read-only by the API so all clients stay consistent; the UI decides
whether to show it (the "Показывать пояснения" preference, on by default).
"""

from __future__ import annotations

from dataclasses import asdict, dataclass


