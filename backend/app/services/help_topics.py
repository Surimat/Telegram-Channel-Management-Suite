_TOPICS_BY_KEY = {topic.key: topic for topic in HELP_TOPICS}


def topic(key: str) -> HelpTopic | None:
    """Return one help topic by key (``None`` when unknown)."""
    return _TOPICS_BY_KEY.get(key)


def all_topics() -> list[dict[str, str]]:
    """Return the whole catalog as plain dictionaries (JSON-friendly)."""
    return [t.as_dict() for t in HELP_TOPICS]


